#!/usr/bin/env python3
"""File-disjoint review ledger for parser/interpreter snapshots.

Concurrency model: the generated base ledger is immutable; every agent owns one
append-only verdict file and one claim file.  Claims are taken under a lock and
written to ``claims/<owner>.txt`` so two agents can never claim the same sid.
``status`` still verifies disjointness and fails loudly if claim files overlap.

Layout under ``--root`` (default ``review/``)::

    ledger.csv              generated by seed: sid,cid,role,sentence,out_sha1,
                            shape_sha1,verdict,note
    meta.json               corpus, snapshot path, counts
    occurrences.json        sentence -> occurrence count (from the snapshot)
    claims/<owner>.txt      one sid per line
    verdicts/<owner>.csv    sid,verdict,note (append-only)
    batches/<owner>.json    last batch handed to an owner

Commands::

    review.py seed    --snapshot snap.json [--out review/ledger.csv]
    review.py batch   --owner a1 [--n 400] [--extend]
    review.py status
    review.py verdict --owner a1 --sid X --verdict bug|ok|legit|unparsed|inspected --note "..."
    review.py check   --owner a1

Every command takes ``--root`` so tests and parallel work can use separate
directories.  Verdicts are only accepted for sids claimed by that owner.

``seed`` and ``batch`` accept ``--exempt review/loop_inspected.txt`` (lines
``sid<TAB>corpora``): matching sids are seeded as ``inspected`` rather than
``todo`` and are never batched unless ``--include-exempt`` is passed.
`batch` also caps the file at ``--max-bytes`` (default 250000) and reports the
actual bytes/row.
"""
import os as _os, sys as _sys
_sys.path.insert(0, _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__))))
import paths as _paths
_paths.bootstrap()

import argparse
import csv
import fcntl
import hashlib
import io
import json
import os
import re
import sys
import time
from collections import Counter, defaultdict

VERDICTS = ("ok", "bug", "legit", "unparsed", "inspected")
OWNER_RE = re.compile(r"^[A-Za-z0-9_.-]+$")


def sid_of(text):
    return hashlib.sha1(text.encode()).hexdigest()[:12]


def cid_of(cluster):
    return hashlib.sha1(cluster.encode()).hexdigest()[:12]


def paths_for(root):
    return {
        "root": root,
        "ledger": os.path.join(root, "ledger.csv"),
        "meta": os.path.join(root, "meta.json"),
        "occurrences": os.path.join(root, "occurrences.json"),
        "claims": os.path.join(root, "claims"),
        "verdicts": os.path.join(root, "verdicts"),
        "batches": os.path.join(root, "batches"),
        "lock": os.path.join(root, "claims", ".lock"),
    }


def ensure_dirs(p):
    for key in ("root", "claims", "verdicts", "batches"):
        os.makedirs(p[key], exist_ok=True)


class _Lock:
    def __init__(self, path):
        self.path = path
        self.fh = None

    def __enter__(self):
        os.makedirs(os.path.dirname(self.path), exist_ok=True)
        self.fh = open(self.path, "a")
        fcntl.flock(self.fh, fcntl.LOCK_EX)
        return self

    def __exit__(self, *exc):
        fcntl.flock(self.fh, fcntl.LOCK_UN)
        self.fh.close()


def read_ledger(p):
    if not os.path.exists(p["ledger"]):
        sys.exit("no ledger at %s (run seed first)" % p["ledger"])
    with open(p["ledger"], newline="") as fh:
        rows = list(csv.DictReader(fh))
    seen = set()
    for row in rows:
        sid = row.get("sid")
        if sid in seen:
            sys.exit("duplicate sid %s in %s (re-run seed)" % (sid, p["ledger"]))
        seen.add(sid)
    return rows


def read_claims(p):
    """{sid: [owner, ...]} plus {owner: [sid, ...]}."""
    by_sid = defaultdict(list)
    by_owner = {}
    if not os.path.isdir(p["claims"]):
        return by_sid, by_owner
    for name in sorted(os.listdir(p["claims"])):
        if name.startswith(".") or not name.endswith(".txt"):
            continue
        owner = name[:-4]
        sids = []
        with open(os.path.join(p["claims"], name)) as fh:
            for line in fh:
                sid = line.strip()
                if sid:
                    sids.append(sid)
                    by_sid[sid].append(owner)
        by_owner[owner] = sids
    return by_sid, by_owner


def read_verdicts(p):
    """{owner: {sid: (verdict, note)}}; rejects duplicate sids."""
    out = {}
    if not os.path.isdir(p["verdicts"]):
        return out
    for name in sorted(os.listdir(p["verdicts"])):
        if name.startswith(".") or not name.endswith(".csv"):
            continue
        owner = name[:-4]
        rows = {}
        with open(os.path.join(p["verdicts"], name), newline="") as fh:
            for row in csv.DictReader(fh):
                sid = row.get("sid")
                if not sid:
                    continue
                if sid in rows:
                    sys.exit("duplicate verdict for sid %s in %s" % (sid, name))
                rows[sid] = (row.get("verdict", ""), row.get("note", ""))
        out[owner] = rows
    return out


def read_exempt(path):
    """sids already read by the audit loops: ``sid<TAB>corpora`` per line."""
    out = set()
    if not path:
        return out
    if not os.path.exists(path):
        sys.exit("exempt file not found: %s" % path)
    with open(path) as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            out.add(line.split("\t")[0].strip())
    return out


def combined_verdicts(ledger, verdicts):
    """Effective verdict per sid: owner verdict file, else the ledger value."""
    eff = {row["sid"]: row.get("verdict") or "todo" for row in ledger}
    for owner, rows in verdicts.items():
        for sid, (verdict, _note) in rows.items():
            eff[sid] = verdict
    return eff


# ----------------------------------------------------------------------- seed
def seed(args):
    with open(args.snapshot) as fh:
        snap = json.load(fh)
    meta = snap.get("meta", {})
    sentences = snap.get("sentences", {})
    unparsed = snap.get("unparsed", []) if args.include_unparsed else []
    exempt = read_exempt(args.exempt)

    clusters = defaultdict(list)
    for text, rec in sentences.items():
        clusters[rec["cluster"]].append(text)

    sid_map = {}
    rows = []
    for cluster in sorted(clusters):
        members = sorted(clusters[cluster])
        counts = Counter(sentences[t]["shape_sha1"] for t in members)
        majority_shape = sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[0][0]
        # the representative must have the majority shape, or it would also be
        # emitted twice (once as majority, once as a deviating minority)
        rep = min(t for t in members
                  if sentences[t]["shape_sha1"] == majority_shape)
        sid = sid_of(rep)
        _check_sid(sid_map, sid, rep)
        cid = cid_of(cluster)
        rows.append({"sid": sid, "cid": cid, "role": "majority",
                     "sentence": rep, "out_sha1": sentences[rep]["out_sha1"],
                     "shape_sha1": majority_shape,
                     "verdict": "inspected" if sid in exempt else "todo",
                     "note": ""})
        for text in members:
            if sentences[text]["shape_sha1"] == majority_shape:
                continue
            sid = sid_of(text)
            _check_sid(sid_map, sid, text)
            rows.append({"sid": sid, "cid": cid, "role": "minority",
                         "sentence": text, "out_sha1": sentences[text]["out_sha1"],
                         "shape_sha1": sentences[text]["shape_sha1"],
                         "verdict": "inspected" if sid in exempt else "todo",
                         "note": ""})
    for text in sorted(unparsed):
        sid = sid_of(text)
        if sid in sid_map:
            continue
        _check_sid(sid_map, sid, text)
        rows.append({"sid": sid, "cid": "", "role": "unparsed",
                     "sentence": text, "out_sha1": "", "shape_sha1": "",
                     "verdict": "inspected" if sid in exempt else "todo",
                     "note": ""})

    rows.sort(key=lambda r: (r["role"] != "unparsed", r["cid"], r["role"], r["sentence"]))
    out = args.out or os.path.join(args.root, "ledger.csv")
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    tmp = out + ".tmp"
    with open(tmp, "w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=["sid", "cid", "role", "sentence",
                                                "out_sha1", "shape_sha1",
                                                "verdict", "note"])
        writer.writeheader()
        writer.writerows(rows)
    os.replace(tmp, out)

    p = paths_for(os.path.dirname(os.path.abspath(out)))
    ensure_dirs(p)
    occurrences = meta.get("occurrences", {})
    with open(p["occurrences"], "w") as fh:
        json.dump(occurrences, fh, sort_keys=True)
    with open(p["meta"], "w") as fh:
        json.dump({"corpus": meta.get("corpus"),
                   "snapshot": os.path.abspath(args.snapshot),
                   "counts": dict(Counter(r["role"] for r in rows)),
                   "generated": time.strftime("%Y-%m-%dT%H:%M:%S")}, fh)
    counts = Counter(r["role"] for r in rows)
    inspected = sum(1 for row in rows if row["verdict"] == "inspected")
    print(json.dumps({"ledger": out, "rows": len(rows),
                      "clusters": len(clusters), "roles": dict(counts),
                      "inspected": inspected, "exempt_sids": len(exempt),
                      "unparsed_in_snapshot": len(unparsed)}, indent=1))
    return 0


def _check_sid(sid_map, sid, text):
    old = sid_map.get(sid)
    if old is not None and old != text:
        sys.exit("sid collision for %r and %r" % (old, text))
    sid_map[sid] = text


# ---------------------------------------------------------------------- batch
def _priority(row, occurrences, state="todo"):
    role = row["role"]
    rank = 0 if role == "unparsed" else (1 if role == "minority" else 2)
    if state == "inspected":
        rank += 3          # inspected rows are strictly lower priority than todo
    return (rank, -occurrences.get(row["sentence"], 0), row["cid"], row["sid"])


def _load_snapshot(p):
    meta_path = p["meta"]
    if not os.path.exists(meta_path):
        return None, defaultdict(list)
    with open(meta_path) as fh:
        meta = json.load(fh)
    snapshot_path = meta.get("snapshot")
    if not snapshot_path or not os.path.exists(snapshot_path):
        return None, defaultdict(list)
    with open(snapshot_path) as fh:
        snap = json.load(fh)
    members = defaultdict(list)
    for text, rec in snap.get("sentences", {}).items():
        members[rec.get("cluster")].append(text)
    return snap, members


def _batch_item(row, snap, members, occurrences):
    item = {"sid": row["sid"], "sentence": row["sentence"], "corpus": None,
            "occurrences": occurrences.get(row["sentence"], 0),
            "cid": row["cid"], "role": row["role"], "output": None,
            "siblings": []}
    if snap is None:
        return item
    item["corpus"] = snap.get("meta", {}).get("corpus")
    item["output"] = snap.get("outputs", {}).get(row["sentence"])
    cluster = snap.get("sentences", {}).get(row["sentence"], {}).get("cluster")
    if cluster is not None:
        peers = sorted(t for t in members.get(cluster, [])
                       if t != row["sentence"])
        for peer in peers[:2]:
            item["siblings"].append({"sentence": peer,
                                     "output": snap["outputs"].get(peer)})
    return item


def batch(args):
    p = paths_for(args.root)
    ensure_dirs(p)
    if not OWNER_RE.match(args.owner):
        sys.exit("invalid owner name %r" % args.owner)
    ledger = read_ledger(p)
    verdicts = read_verdicts(p)
    effective = combined_verdicts(ledger, verdicts)
    exempt = read_exempt(args.exempt)
    occurrences = {}
    if os.path.exists(p["occurrences"]):
        with open(p["occurrences"]) as fh:
            occurrences = json.load(fh)
    snap, members = _load_snapshot(p)
    claim_path = os.path.join(p["claims"], args.owner + ".txt")

    if os.path.exists(claim_path) and not args.extend:
        sys.exit("owner %s already has claims in %s (use --extend)"
                 % (args.owner, claim_path))

    def state_of(sid):
        state = effective.get(sid, "todo")
        if state == "todo" and sid in exempt:
            state = "inspected"
        return state

    allowed = {"todo"} | ({"inspected"} if args.include_exempt else set())
    # reserve the envelope (~3 KB) and the sids list (16 B per sid)
    budget = max(1000, args.max_bytes - 3000 - 16 * args.n)

    with _Lock(p["lock"]):
        by_sid, by_owner = read_claims(p)
        own = list(by_owner.get(args.owner, []))
        claimed = set(by_sid)
        candidates = [r for r in ledger
                      if r["sid"] not in claimed
                      and state_of(r["sid"]) in allowed]
        candidates.sort(key=lambda r: _priority(r, occurrences, state_of(r["sid"])))
        chosen, items, size = [], [], 0
        for row in candidates:
            if len(chosen) >= args.n:
                break
            item = _batch_item(row, snap, members, occurrences)
            # over-estimate: pretty-printed rows grow when nested under "items"
            cost = int(len(json.dumps(item, ensure_ascii=False)) * 1.15) + 200
            if chosen and size + cost > budget:
                break
            chosen.append(row)
            items.append(item)
            size += cost

        if chosen:
            if os.path.exists(claim_path):
                new = own + [r["sid"] for r in chosen]
                tmp = claim_path + ".tmp"
                with open(tmp, "w") as fh:
                    fh.write("\n".join(new) + "\n")
                os.replace(tmp, claim_path)
            else:
                fd = os.open(claim_path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
                with os.fdopen(fd, "w") as fh:
                    fh.write("\n".join(r["sid"] for r in chosen) + "\n")

    batch_doc = {"owner": args.owner, "created": time.strftime("%Y-%m-%dT%H:%M:%S"),
                 "count": len(items), "sids": [r["sid"] for r in chosen],
                 "items": items}
    out = args.out or os.path.join(p["batches"], args.owner + ".json")
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    tmp = out + ".tmp"
    with open(tmp, "w") as fh:
        json.dump(batch_doc, fh, indent=1, ensure_ascii=False)
    os.replace(tmp, out)
    size = os.path.getsize(out)
    if size > args.max_bytes:
        print("warning: batch is %d bytes (> --max-bytes %d); one row is larger "
              "than the budget" % (size, args.max_bytes), file=sys.stderr)
    print(json.dumps({"owner": args.owner, "claimed": len(chosen),
                      "total_claims": len(own) + len(chosen),
                      "batch": out, "bytes": size,
                      "bytes_per_row": round(size / max(1, len(items)), 1),
                      "sids": batch_doc["sids"]}, indent=1))
    return 0


# --------------------------------------------------------------------- status
def status(args):
    p = paths_for(args.root)
    ledger = read_ledger(p)
    verdicts = read_verdicts(p)
    by_sid, by_owner = read_claims(p)
    effective = combined_verdicts(ledger, verdicts)
    rows = {r["sid"]: r for r in ledger}

    dupes = {sid: owners for sid, owners in by_sid.items() if len(owners) > 1}
    unknown = sorted(set(by_sid) - set(rows))
    bad_verdicts = sorted(
        sid for rows in verdicts.values() for sid, (v, _n) in rows.items()
        if v not in VERDICTS)

    states = Counter()
    per_owner = defaultdict(Counter)
    for sid, row in rows.items():
        state = effective.get(sid, "todo")
        if state == "todo" and sid in by_sid:
            state = "claimed"
        states[state] += 1
        for owner in by_sid.get(sid, []):
            per_owner[owner][state] += 1

    print("%-10s %8s" % ("state", "total"))
    for state in ("todo", "claimed", "ok", "bug", "legit", "unparsed", "inspected"):
        print("%-10s %8d" % (state, states.get(state, 0)))
    if per_owner:
        owners = sorted(per_owner)
        print("\n%-10s %8s  %s" % ("owner", "claimed", "states"))
        for owner in owners:
            claimed = len(by_owner.get(owner, []))
            detail = ", ".join("%s=%d" % (s, n) for s, n in sorted(per_owner[owner].items()))
            print("%-10s %8d  %s" % (owner, claimed, detail))
    if dupes:
        print("\nERROR: sid claimed by more than one owner:", file=sys.stderr)
        for sid, owners in sorted(dupes.items()):
            print("  %s -> %s (%s)" % (sid, owners, rows.get(sid, {}).get("sentence")),
                  file=sys.stderr)
    if unknown:
        print("\nERROR: claims for unknown sids: %s" % ", ".join(unknown),
              file=sys.stderr)
    if bad_verdicts:
        print("\nERROR: invalid verdicts for: %s" % ", ".join(bad_verdicts),
              file=sys.stderr)
    return 1 if (dupes or unknown or bad_verdicts) else 0


# -------------------------------------------------------------------- verdict
def _append_verdict(path, sid, verdict, note):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "a+", newline="") as fh:
        fcntl.flock(fh, fcntl.LOCK_EX)
        try:
            fh.seek(0, os.SEEK_END)
            if fh.tell() == 0:
                fh.write("sid,verdict,note\n")
            buf = io.StringIO()
            csv.writer(buf).writerow([sid, verdict, note])
            fh.write(buf.getvalue())
            fh.flush()
        finally:
            fcntl.flock(fh, fcntl.LOCK_UN)


def verdict(args):
    if args.verdict not in VERDICTS:
        sys.exit("verdict must be one of %s" % (VERDICTS,))
    if not OWNER_RE.match(args.owner):
        sys.exit("invalid owner name %r" % args.owner)
    p = paths_for(args.root)
    ledger = read_ledger(p)
    rows = {r["sid"]: r for r in ledger}
    if args.sid not in rows:
        sys.exit("unknown sid %s" % args.sid)
    by_sid, by_owner = read_claims(p)
    if args.owner not in by_sid.get(args.sid, []):
        sys.exit("sid %s is not claimed by %s" % (args.sid, args.owner))
    verdicts = read_verdicts(p)
    existing = verdicts.get(args.owner, {}).get(args.sid)
    if existing:
        if existing[0] == args.verdict:
            print("already recorded: %s %s" % (args.sid, args.verdict))
            return 0
        sys.exit("conflicting verdict: sid %s already %r for %s"
                 % (args.sid, existing[0], args.owner))
    path = os.path.join(p["verdicts"], args.owner + ".csv")
    _append_verdict(path, args.sid, args.verdict, args.note or "")
    print("recorded %s %s" % (args.sid, args.verdict))
    return 0


# ---------------------------------------------------------------------- check
def check(args):
    p = paths_for(args.root)
    ledger = read_ledger(p)
    rows = {r["sid"]: r for r in ledger}
    by_sid, by_owner = read_claims(p)
    verdicts = read_verdicts(p)
    own = by_owner.get(args.owner, [])
    own_verdicts = verdicts.get(args.owner, {})
    missing = sorted(sid for sid in own if sid not in own_verdicts)
    extra = sorted(sid for sid in own_verdicts if sid not in set(own))
    unknown = sorted(sid for sid in own if sid not in rows)
    if missing:
        print("missing verdicts: %d" % len(missing))
        for sid in missing:
            print("  %s  %s" % (sid, rows.get(sid, {}).get("sentence", "?")))
    if extra:
        print("verdicts for sids not claimed by %s: %s" % (args.owner, ", ".join(extra)),
              file=sys.stderr)
    if unknown:
        print("claims for unknown sids: %s" % ", ".join(unknown), file=sys.stderr)
    ok = not (missing or extra or unknown)
    print("%s: %d claimed, %d verdicts, %s" % (args.owner, len(own),
                                               len(own_verdicts),
                                               "complete" if ok else "INCOMPLETE"))
    return 0 if ok else 1


def main(argv=None):
    ap = argparse.ArgumentParser(description="File-disjoint review ledger.")
    sub = ap.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("seed", help="generate the base ledger from a snapshot")
    s.add_argument("--snapshot", required=True)
    s.add_argument("--out", default=None,
                   help="ledger path (default <root>/ledger.csv)")
    s.add_argument("--root", default="review")
    s.add_argument("--include-unparsed", action="store_true", default=True,
                   help="seed rows for snapshot['unparsed'] (default on)")
    s.add_argument("--no-unparsed", dest="include_unparsed", action="store_false")
    s.add_argument("--exempt", default=None,
                   help="sid<TAB>corpora file already read by the audit loops")

    b = sub.add_parser("batch", help="claim todo sids and write a batch")
    b.add_argument("--owner", required=True)
    b.add_argument("--n", type=int, default=400)
    b.add_argument("--extend", action="store_true")
    b.add_argument("--out", default=None)
    b.add_argument("--root", default="review")
    b.add_argument("--exempt", default=None,
                   help="sid<TAB>corpora file; matching sids become inspected")
    b.add_argument("--include-exempt", action="store_true",
                   help="also assign previously inspected rows")
    b.add_argument("--max-bytes", type=int, default=250000,
                   help="size budget for the batch file (default 250000)")

    st = sub.add_parser("status", help="state table and claim-disjointness check")
    st.add_argument("--root", default="review")

    v = sub.add_parser("verdict", help="append one verdict")
    v.add_argument("--owner", required=True)
    v.add_argument("--sid", required=True)
    v.add_argument("--verdict", required=True)
    v.add_argument("--note", default="")
    v.add_argument("--root", default="review")

    c = sub.add_parser("check", help="every claimed sid has exactly one verdict")
    c.add_argument("--owner", required=True)
    c.add_argument("--root", default="review")

    args = ap.parse_args(argv)
    return {"seed": seed, "batch": batch, "status": status,
            "verdict": verdict, "check": check}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
